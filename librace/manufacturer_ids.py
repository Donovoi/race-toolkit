APPLE_COMPANY_ID = "004c"
MICROSOFT_COMPANY_ID = "0006"
GOOGLE_COMPANY_ID = "00e0"
SAMSUNG_COMPANY_ID = "0075"
SONY_COMPANY_ID = "012d"
BOSE_COMPANY_ID = "009e"
XIAOMI_COMPANY_ID = "0157"
HUAWEI_COMPANY_ID = "027d"
NORDIC_SEMICONDUCTOR_COMPANY_ID = "0059"
QUALCOMM_COMPANY_ID = "001d"


def lookup_manufacturer(code: str) -> Optional[str]:
    """Look up a manufacturer by company ID.

    Args:
        code: The company ID as a 4-character hex string (e.g., "004c" for Apple)
              or as an integer that will be converted to hex.

    Returns:
        Company name if found, None otherwise.

    Example:
        >>> lookup_manufacturer("004c")
        'Apple, Inc.'
        >>> lookup_manufacturer("0006")
        'Microsoft'
    """
    if isinstance(code, int):
        code = f"{code:04x}"
    return MANUFACTURER_COMPANY_IDS.get(code.lower())


def lookup_manufacturer_by_int(company_id: int) -> Optional[str]:
    """Look up a manufacturer by integer company ID.

    Args:
        company_id: The company ID as an integer (e.g., 76 for Apple)

    Returns:
        Company name if found, None otherwise.

    Example:
        >>> lookup_manufacturer_by_int(76)
        'Apple, Inc.'
    """
    return lookup_manufacturer(f"{company_id:04x}")


def parse_manufacturer_data(data: bytes) -> tuple[Optional[str], bytes]:
    """Parse manufacturer-specific data from BLE advertisement.

    The first two bytes of manufacturer data contain the company ID
    in little-endian format, followed by manufacturer-specific payload.

    Args:
        data: Raw manufacturer data bytes (minimum 2 bytes)

    Returns:
        Tuple of (company_name, payload_bytes).
        company_name is None if the company ID is not recognized.

    Example:
        >>> parse_manufacturer_data(bytes.fromhex("4c000215..."))
        ('Apple, Inc.', b'\\x02\\x15...')
    """
    if len(data) < 2:
        return (None, data)

    # Company ID is little-endian
    company_id = int.from_bytes(data[:2], byteorder="little")
    company_code = f"{company_id:04x}"
    company_name = lookup_manufacturer(company_code)
    payload = data[2:]

    return (company_name, payload)
